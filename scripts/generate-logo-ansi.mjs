/**
 * Pre-renders the autousers brand mark to TWO formats and writes them as
 * constants in `src/tui/assets/logo-ansi.ts`:
 *
 *   LOGO_ITERM2  — iTerm2 inline-image protocol escape. Embeds the actual
 *                  PNG as base64 wrapped in OSC 1337. Renders crisp pixel-
 *                  perfect output in iTerm2, Warp, WezTerm, Ghostty,
 *                  Kitty, etc. Ignored / shows garbage in unsupporting
 *                  terminals — header.tsx must feature-detect.
 *
 *   LOGO_BLOCKS  — Truecolor half-block ANSI fallback. Renders correctly
 *                  in any terminal with truecolor support (works in
 *                  basically everything, including macOS Terminal.app).
 *                  Lower fidelity than the inline image but universal.
 *
 * Source PNG: `public/logo/autousers_logo@2x.png` (224×224 px) — the @2x
 * gives terminal-image more pixels to downsample from, so the half-block
 * fallback comes out sharper than rendering from the 1x.
 *
 * Run once when the logo PNG changes:
 *   npm run regen:logo
 *
 * terminal-image is a devDependency only — never ships in the npm
 * tarball; the constant strings are what users see.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Repo root is two dirs up from cli/scripts/.
const LOGO_PATH = path.resolve(
  __dirname,
  "../..",
  "public/logo/autousers_logo@2x.png"
);
const OUT_PATH = path.resolve(__dirname, "..", "src/tui/assets/logo-ansi.ts");

if (!fs.existsSync(LOGO_PATH)) {
  console.error(`Logo PNG not found at ${LOGO_PATH}`);
  process.exit(1);
}

const buf = fs.readFileSync(LOGO_PATH);
const base64 = buf.toString("base64");

// --------------------------------------------------------------------------
// LOGO_ITERM2 — iTerm2/Warp/WezTerm inline-image protocol escape.
// --------------------------------------------------------------------------
// OSC 1337 ESC ] 1337 ; File = [args] : base64data BEL
// width=14 cells, preserveAspectRatio=1, inline=1 (render in-line vs popup).
// `name=` is required for iTerm2 to accept the data; we set a fixed
// filename so the protocol parsers know it's a PNG.
const iterm2 =
  "\x1b]1337;File=name=" +
  Buffer.from("autousers_logo.png").toString("base64") +
  ";size=" +
  buf.length +
  ";inline=1;width=14;height=7;preserveAspectRatio=1:" +
  base64 +
  "\x07";

// --------------------------------------------------------------------------
// LOGO_BLOCKS — universal truecolor half-block fallback.
// --------------------------------------------------------------------------
// We import terminal-image with TERM_PROGRAM stripped + FORCE_COLOR=3 so it
// picks the chalk/half-block render path rather than the iTerm2 protocol
// path it would normally choose when run inside iTerm2 itself.
process.env.TERM_PROGRAM = "";
process.env.LC_TERMINAL = "";
process.env.FORCE_COLOR = "3";
delete process.env.KITTY_WINDOW_ID;
const { default: terminalImage } = await import("terminal-image");

// Width 24 (vs the previous 14) — gives 24×24 effective pixels, which is
// noticeably sharper for the round-Ä mark. Doubling width quadruples the
// detail vs the prior 14×14 render.
const blocks = await terminalImage.buffer(buf, { width: 24 });

// --------------------------------------------------------------------------
// Write the TS file
// --------------------------------------------------------------------------
const ts =
  "// AUTO-GENERATED by cli/scripts/generate-logo-ansi.mjs — DO NOT EDIT.\n" +
  "// Re-run `npm run regen:logo` from cli/ after changing\n" +
  "// public/logo/autousers_logo@2x.png.\n" +
  "//\n" +
  "// Two pre-rendered representations of the autousers brand mark:\n" +
  "//   LOGO_ITERM2 — iTerm2/Warp/WezTerm/Ghostty/Kitty inline-image escape\n" +
  "//                 (perfect crispness, but only renders on supported terms)\n" +
  "//   LOGO_BLOCKS — Truecolor half-block fallback (universal)\n" +
  "//\n" +
  "// header.tsx feature-detects and picks the right one.\n" +
  "//\n" +
  `export const LOGO_ITERM2 = ${JSON.stringify(iterm2)};\n` +
  `export const LOGO_BLOCKS = ${JSON.stringify(blocks)};\n`;

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, ts);
console.log(
  `Wrote ${OUT_PATH}\n` +
    `  LOGO_ITERM2: ${iterm2.length} bytes (PNG ${buf.length} bytes inline)\n` +
    `  LOGO_BLOCKS: ${blocks.length} bytes ANSI, ${blocks.split("\n").length} lines`
);
